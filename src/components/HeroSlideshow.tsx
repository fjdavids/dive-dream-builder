import { useState, useEffect, useRef, useCallback } from 'react';
import { ArrowRight } from 'lucide-react';
import { Button } from '@/components/ui/button';
import { Link } from 'react-router-dom';
import { useLanguage } from '@/contexts/LanguageContext';

// Original JPGs stay as the universal fallback <img src>.
import snorkelingturtleImg from '@/assets/snorkeling-turtle.jpg';
import reefDiveImg from '@/assets/reef-dive-divelife.jpg';
import familyScubaImg from '@/assets/family-scuba-divelife.jpg';
import sailingImg from '@/assets/luxury-catamaran-new.jpg';
import seabobActionImg from '@/assets/seabob-action-divelife.jpg';

// Compressed AVIF/WebP variants generated by scripts/optimize-images.py:
//   <name>-d<width>  desktop/tablet (original ratio)
//   <name>-m<width>  mobile (centre 3:4 crop = what object-cover shows on phones)
const HERO_VARIANTS = import.meta.glob<string>('/src/assets/hero/*.{avif,webp}', {
  eager: true,
  query: '?url',
  import: 'default',
}) as Record<string, string>;

function buildSrcSet(name: string, kind: 'd' | 'm', ext: 'avif' | 'webp'): string | undefined {
  const re = new RegExp(`/${name}-${kind}(\\d+)\\.${ext}$`);
  const list = Object.entries(HERO_VARIANTS)
    .map(([path, url]) => {
      const m = path.match(re);
      return m ? { url, w: Number(m[1]) } : null;
    })
    .filter((v): v is { url: string; w: number } => v !== null)
    .sort((a, b) => a.w - b.w);
  return list.length ? list.map((v) => `${v.url} ${v.w}w`).join(', ') : undefined;
}

const slides = [
  { name: 'snorkeling-turtle', src: snorkelingturtleImg, altEn: 'Snorkeler swimming beside a sea turtle in the Caribbean reef', altEs: 'Snorkeler nadando junto a una tortuga marina en el arrecife del Caribe' },
  { name: 'reef-dive-divelife', src: reefDiveImg, altEn: 'Scuba diver exploring a coral reef in Playa del Carmen', altEs: 'Buzo explorando un arrecife de coral en Playa del Carmen' },
  { name: 'family-scuba-divelife', src: familyScubaImg, altEn: 'Family learning to scuba dive with a PADI instructor', altEs: 'Familia aprendiendo a bucear con un instructor PADI' },
  { name: 'luxury-catamaran-new', src: sailingImg, altEn: 'Luxury catamaran sailing along the Riviera Maya coastline', altEs: 'Catamarán de lujo navegando por la costa de la Riviera Maya' },
  { name: 'seabob-action-divelife', src: seabobActionImg, altEn: 'Guest riding a Seabob underwater scooter over turquoise water', altEs: 'Huésped montando un Seabob sobre aguas turquesa' },
];

const heroImages = slides.map((s) => ({
  ...s,
  mAvif: buildSrcSet(s.name, 'm', 'avif'),
  mWebp: buildSrcSet(s.name, 'm', 'webp'),
  dAvif: buildSrcSet(s.name, 'd', 'avif'),
  dWebp: buildSrcSet(s.name, 'd', 'webp'),
}));

const MOBILE_MQ = '(max-width: 767px)';

export default function HeroSlideshow() {
  const { t, language } = useLanguage();
  const [currentIndex, setCurrentIndex] = useState(0);
  // Only slides that are mounted get downloaded. Slide 0 is the LCP image;
  // the next slide is mounted (and fetched) shortly before it is needed.
  const [mounted, setMounted] = useState<Set<number>>(() => new Set([0]));
  const [ready, setReady] = useState(false);
  const loadedRef = useRef<Set<number>>(new Set());
  const pendingRef = useRef<number | null>(null);
  const currentRef = useRef(0);
  currentRef.current = currentIndex;

  const mount = useCallback((i: number) => {
    setMounted((prev) => (prev.has(i) ? prev : new Set(prev).add(i)));
  }, []);

  // Switch only once the target slide has loaded, so a slow network never
  // fades to an empty frame; until then the current photo stays visible.
  const goTo = useCallback(
    (i: number) => {
      if (loadedRef.current.has(i)) {
        pendingRef.current = null;
        setCurrentIndex(i);
      } else {
        pendingRef.current = i;
        mount(i);
      }
    },
    [mount],
  );

  const handleLoad = useCallback((i: number) => {
    loadedRef.current.add(i);
    if (i === 0) {
      // Start fetching the rest only after the page has finished loading.
      const start = () => {
        const ric = (window as Window & { requestIdleCallback?: (cb: () => void, o?: { timeout: number }) => number }).requestIdleCallback;
        if (ric) ric(() => setReady(true), { timeout: 1500 });
        else setTimeout(() => setReady(true), 300);
      };
      if (document.readyState === 'complete') start();
      else window.addEventListener('load', start, { once: true });
    }
    if (pendingRef.current === i) {
      pendingRef.current = null;
      setCurrentIndex(i);
    }
  }, []);

  // Preload the upcoming slide while the current one is on screen.
  useEffect(() => {
    if (!ready) return;
    mount((currentIndex + 1) % heroImages.length);
  }, [ready, currentIndex, mount]);

  useEffect(() => {
    const interval = setInterval(() => {
      goTo((currentRef.current + 1) % heroImages.length);
    }, 4000);
    return () => clearInterval(interval);
  }, [goTo]);

  return (
    <section className="relative min-h-[620px] md:min-h-[760px] flex items-end overflow-hidden">
      {/* Background Images with Crossfade */}
      <div className="absolute inset-0">
        {heroImages.map((image, index) => {
          if (!mounted.has(index)) return null;
          const isFirst = index === 0;
          return (
            <div
              key={index}
              className="absolute inset-0 transition-opacity duration-1500"
              style={{
                opacity: index === currentIndex ? 1 : 0,
                zIndex: index === currentIndex ? 1 : 0,
              }}
              {...(isFirst ? {} : { 'data-prerender-skip': '' })}
            >
              <picture>
                {image.mAvif && <source media={MOBILE_MQ} type="image/avif" srcSet={image.mAvif} sizes="100vw" />}
                {image.mWebp && <source media={MOBILE_MQ} type="image/webp" srcSet={image.mWebp} sizes="100vw" />}
                {image.dAvif && <source type="image/avif" srcSet={image.dAvif} sizes="100vw" />}
                {image.dWebp && <source type="image/webp" srcSet={image.dWebp} sizes="100vw" />}
                <img
                  ref={(el) => {
                    if (el && el.complete && el.naturalWidth > 0 && !loadedRef.current.has(index)) handleLoad(index);
                  }}
                  src={image.src}
                  alt={language === 'es' ? image.altEs : image.altEn}
                  width={1920}
                  height={1080}
                  className="w-full h-full object-cover"
                  onLoad={() => {
                    if (!loadedRef.current.has(index)) handleLoad(index);
                  }}
                  decoding="async"
                  loading="eager"
                  fetchPriority={isFirst ? 'high' : 'low'}
                />
              </picture>
            </div>
          );
        })}
        {/* Subtle, functional legibility overlay only */}
        <div className="absolute inset-0 z-10 bg-gradient-to-t from-ocean-deep/90 via-ocean-deep/55 to-ocean-deep/30" />
      </div>

      {/* Hero Content — editorial, left aligned */}
      <div className="relative z-20 container pb-20 pt-32 md:pb-28 md:pt-40 text-ivory">
        <div className="max-w-[46rem]">
          <p className="eyebrow mb-6 text-ivory animate-fade-in">{t.footer.padi}</p>
          <h1 className="mb-6 animate-fade-in text-ivory">
            {t.hero.title}
          </h1>
          <p className="mb-9 max-w-[44rem] text-[0.9375rem] leading-relaxed animate-fade-in text-ivory/90 md:text-base">
            {t.hero.subtitle}
          </p>
          <div className="flex flex-wrap items-center gap-x-8 gap-y-4 animate-fade-in">
            <Button size="lg" className="bg-ivory text-ocean-deep hover:bg-white" asChild>
              <Link to="/experiences">{language === 'es' ? 'Explorar experiencias' : 'Explore Experiences'}</Link>
            </Button>
            <Link to={`/availability?lang=${language}`} className="link-editorial text-ivory">
              {language === 'es' ? 'Consultar disponibilidad' : 'Check Availability'}
              <ArrowRight className="h-4 w-4" />
            </Link>
          </div>
        </div>
      </div>

      {/* Slideshow Indicators */}
      <div className="absolute bottom-8 right-6 md:right-10 z-20 flex gap-2">
        {heroImages.map((_, index) => (
          <button
            key={index}
            onClick={() => goTo(index)}
            className={`h-[2px] transition-all duration-300 ${
              index === currentIndex
                ? 'bg-ivory w-10'
                : 'bg-ivory/45 hover:bg-ivory/80 w-5'
            }`}
            aria-label={`Go to slide ${index + 1}`}
          />
        ))}
      </div>
    </section>
  );
}
